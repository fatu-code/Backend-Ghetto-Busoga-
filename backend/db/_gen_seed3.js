function genderOf(name) {
  const toks = name.trim().split(/\s+/);
  const last = toks[toks.length - 1].toUpperCase();
  if (FEMALE.has(last)) return 'Female';
  if (MALE.has(last)) return 'Male';
  // try the token before last (some have surname last)
  if (toks.length > 1) {
    const prev = toks[toks.length - 2].toUpperCase();
    if (FEMALE.has(prev)) return 'Female';
    if (MALE.has(prev)) return 'Male';
  }
  return null;
}
